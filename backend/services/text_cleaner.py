import re
import unicodedata


class TextCleaner:

    @staticmethod
    def clean(text: str) -> str:

        if not text:
            return ""

        ############################################################
        # Unicode normalization
        ############################################################

        text = unicodedata.normalize("NFKC", text)

        ############################################################
        # Normalize newlines
        ############################################################

        text = text.replace("\r\n", "\n")
        text = text.replace("\r", "\n")

        ############################################################
        # Normalize tabs
        ############################################################

        text = text.replace("\t", " ")

        ############################################################
        # Replace common unicode punctuation
        ############################################################

        replacements = {

            "•": "-",

            "▪": "-",

            "●": "-",

            "◦": "-",

            "–": "-",

            "—": "-",

            "−": "-",

            "“": '"',

            "”": '"',

            "‘": "'",

            "’": "'",

            "…": "...",

            "ﬁ": "fi",

            "ﬂ": "fl",
        }

        for old, new in replacements.items():
            text = text.replace(old, new)

        ############################################################
        # Remove page numbers
        ############################################################

        text = re.sub(
            r"\n\s*\d+\s*\n",
            "\n",
            text,
        )

        ############################################################
        # Remove repeated separators
        ############################################################

        text = re.sub(
            r"[-_=]{4,}",
            "",
            text,
        )

        ############################################################
        # Remove excessive spaces
        ############################################################

        text = re.sub(
            r"[ ]{2,}",
            " ",
            text,
        )

        ############################################################
        # Remove excessive blank lines
        ############################################################

        text = re.sub(
            r"\n{3,}",
            "\n\n",
            text,
        )

        ############################################################
        # Join wrapped lines
        #
        # Example:
        #
        # Planning
        # Agent
        #
        # ->
        #
        # Planning Agent
        ############################################################

        text = re.sub(
            r"(?<![.!?:])\n(?=[a-zA-Z])",
            " ",
            text,
        )

        ############################################################
        # Trim whitespace
        ############################################################

        return text.strip()